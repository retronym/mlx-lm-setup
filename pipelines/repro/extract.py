"""A bug thread -> a reproducer spec, written by the local LLM and gated mechanically:

  JSON with the schema below; files only when `runnable`; every quoted-output string (`bug_output`, `fixed_output`) copied from the thread; most code lines copied from the
  thread too (wrapping lines such as `object Test extends App {` are allowed, inventing the reproducer is not).

A failed gate is fed back and the model tries again (at most `attempts` times); the last try is returned with its problems, so a spec that never
passed is visible as such rather than silently run."""
import json, os, re, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "search"))
import llm                                                          # pipelines/search/llm.py: chat through the gateway

MODEL = os.environ.get("REPRO_MODEL", "qwen3-coder")
VERSION = 2                                                           # bump when the prompt or the gates change: cached specs are redone
WHY_NOT = ("build", "java", "bytecode", "scaladoc", "repl", "environment", "performance", "tooling", "no_code", "feature")
DIAG_FLAGS = re.compile(r"^-(deprecation|feature|unchecked|Xlint(:[\w,-]+)?|Werror|Xfatal-warnings)$")
SYMPTOMS = ("crash", "spurious_error", "missing_error", "wrong_output", "runtime_exception", "hang", "wrong_warning", "other")

PROMPT = """You turn a Scala compiler bug report into a reproducer that a script can run with scala-cli. Read the whole thread: a later comment
often has a smaller or corrected reproducer; prefer the smallest one that still shows the bug.

Answer with one JSON object, then the reproducer's files as fenced code blocks, each fence naming its file, and nothing else:
{
  "runnable": true | false,
  "why_not": one of "build" (sbt, partest, several modules, separate compilation, macros defined in another compilation unit), "java" (needs
             Java sources), "bytecode" (the bug is in the generated bytecode: javap, fields, signatures, verify errors that need a JVM inspection),
             "scaladoc", "repl" (only shows in the interactive REPL), "environment" (a JDK version, an OS, directory or file names, encodings),
             "performance", "tooling" (IDE, presentation compiler, sbt, Zinc), "no_code" (the thread has no reproducer), "feature" (a request, not a bug),
             or null when runnable,
  "mode": "compile" | "run",
  "files": ["Test.scala"],
  "scalac_options": ["-Xsource:3", ...],
  "deps": ["org.typelevel::cats-core:2.9.0", ...],
  "reported_version": "2.12.8" | null,
  "symptom": one of %s,
  "bug_output": ["a short exact string, copied from output quoted in the thread, that the compiler or program prints BECAUSE of the bug", ...],
  "fixed_output": ["a short exact string from the thread that a FIXED compiler would print and the buggy one does not (a missing warning or error)", ...],
  "expected": "one sentence: what correct behaviour would be"
}
```scala Test.scala
object Test {
  ...
}
```

Rules:
- Only mark runnable when a single scala-cli compile or run of Scala files shows the bug. Otherwise runnable false with why_not.
- Warnings often need flags: you may add -deprecation, -feature, -unchecked or -Xlint (or -Xlint:<name>) when the bug is about a warning.
- Copy the code from the thread. Do not invent code. You may only add what is needed to make it a complete file: an enclosing
  `object Test { ... }`, a `def main(args: Array[String]): Unit = ...` or `extends App`, imports the thread implies.
- REPL transcripts (`scala> ...`): keep the input lines, drop the `scala>` prompts and the REPL's answers, put them in a `Test.scala` object.
  If the bug is about printed results, use mode "run" and println the expressions.
- mode "run" only when the bug shows at run time (wrong output, exception at run time). Otherwise "compile".
- `crash` = the compiler itself throws (stack trace, assertion failure, "error while ..."); `spurious_error` = valid code is rejected;
  `missing_error` = invalid code is accepted (or a warning is missing); `wrong_output` = the program prints the wrong thing.
- `bug_output`: zero to three exact substrings copied from the buggy output quoted in the thread (the spurious error message, the exception
  class, the wrong printed value). `fixed_output`: only when the thread quotes what a correct compiler prints, e.g. the warning that is
  missing. Empty lists when the thread quotes nothing. Never paraphrase them, and never put the expected warning into bug_output.
- Compiler flags go in `scalac_options` (one flag per element), library dependencies in Mill/scala-cli form `org::name:version`.
- Several files only when the bug needs them in one compilation run. No code blocks when not runnable.

The thread (scala/bug#%s, "%s"):

%s"""


def _norm(s):
    return re.sub(r"\s+", " ", s).strip()


WRAPPER = re.compile(r"^(object|class|trait)\s+\w+.*\{?$|^def main\(|^\}+\)?$|^import |^package |^[{}()]+$|^println\(|^extends App|^//")


def check(spec, thread_text):
    """[problems] of a spec against the thread it came from; [] means it passes."""
    p = []
    if not isinstance(spec, dict):
        return ["the answer is not a JSON object"]
    if spec.get("symptom") not in SYMPTOMS:
        p.append(f"symptom must be one of {', '.join(SYMPTOMS)}")
    if not isinstance(spec.get("runnable"), bool):
        p.append("runnable must be true or false")
    norm_thread = _norm(thread_text)
    both = {_norm(e) for e in spec.get("bug_output") or [] if isinstance(e, str)} & {_norm(e) for e in spec.get("fixed_output") or [] if isinstance(e, str)}
    if both:
        p.append(f"{sorted(both)[0]!r} is in both bug_output and fixed_output: the buggy and the fixed compiler cannot both print it")
    for k in ("bug_output", "fixed_output"):
        for e in spec.get(k) or []:
            if not isinstance(e, str) or len(_norm(e)) < 3 or _norm(e) not in norm_thread:
                p.append(f"{k} {e!r} is not copied exactly from the thread; copy a substring (3+ characters) or leave the list empty")
    if spec.get("runnable"):
        if spec.get("mode") not in ("compile", "run"):
            p.append('mode must be "compile" or "run"')
        files = spec.get("files")
        if not files or not all(isinstance(f, dict) and f.get("name", "").endswith((".scala", ".sc", ".java")) and f.get("content") for f in files):
            p.append("give each file in `files` as a fenced code block after the JSON, the fence naming the file: ```scala Test.scala")
        else:
            lines = [_norm(re.sub(r"\s//.*$", "", l)) for f in files for l in f["content"].splitlines()]   # a comment the model added is not code
            lines = [l for l in lines if len(l) > 3 and not WRAPPER.match(l)]
            found = [l for l in lines if l in norm_thread]
            if not found:                                             # nothing to run: an honest "no reproducer", not a failed extraction
                spec.update(runnable=False, why_not=spec.get("why_not") or "no_code", files=[])
                spec.setdefault("repaired", []).append("no code from the thread in the files: not runnable")
            elif len(found) / len(lines) < 0.6:
                missing = [l for l in lines if l not in norm_thread][:3]
                p.append(f"only {len(found)} of {len(lines)} code lines are copied from the thread; copy the thread's code, e.g. these are not in it: {missing}")
        for k in ("scalac_options", "deps"):
            if not isinstance(spec.get(k) or [], list):
                p.append(f"{k} must be a list")
        for o in spec.get("scalac_options") or []:
            if isinstance(o, str) and DIAG_FLAGS.match(o):
                continue
            if not isinstance(o, str) or o.split(":")[0].split("=")[0] not in thread_text:
                p.append(f"scalac option {o!r} is not mentioned in the thread; only use flags the thread uses")
        for d in spec.get("deps") or []:
            name = d.split(":")[-2] if isinstance(d, str) and d.count(":") >= 2 else None
            if not name or name.split("_")[0] not in thread_text:
                p.append(f"dependency {d!r} is not mentioned in the thread")
    v = spec.get("reported_version")
    if v and (not isinstance(v, str) or v not in thread_text):
        p.append(f"reported_version {v!r} is not in the thread; use the version the thread names, or null")
    return p


ANON = re.compile(r"^```(?:scala|sc)?[ \t]*\n(.*?)^```", re.S | re.M)
FENCE = re.compile(r"^```[\w-]*[ \t]+([\w.-]+\.(?:scala|sc|java))[ \t]*\n(.*?)^```", re.S | re.M)


def _json(text):
    """The spec from an answer: the JSON object before the first code fence, with `files` filled from the named fences."""
    head = text.split("```", 1)[0] if not text.lstrip().startswith("```json") else text.split("```json", 1)[1].split("```", 1)[0]
    m = re.search(r"\{.*\}", head, re.S)
    if not m:
        return None
    try:
        spec = json.loads(m.group(0))
    except ValueError:
        return None
    if isinstance(spec, dict):
        blocks = {name: body for name, body in FENCE.findall(text)}
        names = [f if isinstance(f, str) else (f or {}).get("name") for f in spec.get("files") or []] or list(blocks)
        if not blocks:                                                # fences without a file name: take them in order
            anon = ANON.findall(text[len(head):])
            names = [n for n in names if isinstance(n, str)] or [f"Test{i or ''}.scala" for i in range(len(anon))]
            blocks = dict(zip(names, anon))
        if blocks and not any(n in blocks for n in names if isinstance(n, str)):
            names = list(blocks)                                      # the fences name other files than `files` does: trust the fences
        spec["files"] = [_script(n, blocks[n]) for n in names if n in blocks]
    return spec


DEFN = re.compile(r"^(package|import|object|class|trait|case|sealed|abstract|final|private|protected|implicit class|enum|@|//|/\*|\*|\}|\)|$)")


def _script(name, content):
    """A .scala file with top-level statements (`new C()`, `implicit val`, `println(...)`) becomes a scala-cli script, which allows them."""
    if name.endswith(".scala") and any(not DEFN.match(l) for l in content.splitlines() if l and not l[0].isspace()):
        name = name[:-len(".scala")] + ".sc"
    return {"name": name, "content": content}


def repair(spec, thread_text):
    """Drop quoted-output strings that are not in the thread: they are optional, and without them the judge falls back to the symptom's rules."""
    if isinstance(spec, dict):
        if spec.get("runnable") and any(f.get("name", "").endswith(".java") or re.search(r"^\s*public (final )?(class|interface) ", f.get("content", ""), re.M)
                                        for f in spec.get("files") or []):
            spec.update(runnable=False, why_not="java")               # scala-cli without its server does not compile Java sources
            spec.setdefault("repaired", []).append("Java sources: not runnable here")
        t = _norm(thread_text)
        for k in ("bug_output", "fixed_output"):
            if isinstance(spec.get(k), list):
                dropped = [e for e in spec[k] if not (isinstance(e, str) and len(_norm(e)) >= 3 and _norm(e) in t)]
                if dropped:
                    spec[k] = [e for e in spec[k] if e not in dropped]
                    spec.setdefault("repaired", []).append(f"dropped {k} not in the thread: {dropped}")
    return spec


def extract(th, attempts=3):
    """{"spec", "problems", "attempts"} for a thread from issues.thread()."""
    msgs = [{"role": "user", "content": PROMPT % (", ".join(SYMPTOMS), th["number"], th["title"], th["text"])}]
    spec, problems = None, ["no answer"]
    for i in range(1, attempts + 1):
        answer = llm.chat(msgs, MODEL, max_tokens=2500, temperature=0.1 if i == 1 else 0.3)
        spec = repair(_json(answer), th["text"])
        problems = check(spec, th["text"])
        if not problems:
            return {"spec": spec, "problems": [], "attempts": i}
        msgs += [{"role": "assistant", "content": answer},
                 {"role": "user", "content": "That does not pass the checks:\n- " + "\n- ".join(problems) + "\nAnswer again with the corrected JSON object only."}]
    return {"spec": spec, "problems": problems, "attempts": attempts}


if __name__ == "__main__":
    import issues
    print(json.dumps(extract(issues.thread(int(sys.argv[1]))), indent=1))
